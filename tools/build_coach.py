"""Turn the Blender frames of the coach run cycle into compact vector layers.

python tools/build_coach.py <frames_dir> <out_js> [preview_png]

Each frame becomes up to three nested posterised layers (silhouette, mid, lit)
as simplified polygons on an integer grid, which the page fills in green with
increasing brightness. No bitmaps ship with the agent: the data is a few tens
of KB and draws through the same canvas path API as the cadence curve.
"""
import json
import sys
import cv2
import numpy as np
from PIL import Image, ImageDraw

frames_dir, out_js = sys.argv[1], sys.argv[2]
preview = sys.argv[3] if len(sys.argv) > 3 else None
COUNT = 24
SCALE = 0.5            # render px -> grid units
EPS = 1.1              # polygon simplification in render px
MIN_AREA = 14.0        # drop speckles (render px^2)

rgba = [np.array(Image.open('%s/f%02d.png' % (frames_dir, i)).convert('RGBA')) for i in range(COUNT)]
alpha = [im[..., 3] for im in rgba]
lum = [cv2.cvtColor(im[..., :3], cv2.COLOR_RGB2GRAY) for im in rgba]

# Common crop box over all frames so the figure does not jump.
ys, xs = [], []
for a in alpha:
    yy, xx = np.where(a > 128)
    ys += [yy.min(), yy.max()]
    xs += [xx.min(), xx.max()]
pad = 6
x0, x1 = max(0, min(xs) - pad), max(xs) + pad
y0, y1 = max(0, min(ys) - pad), max(ys) + pad
W = int(round((x1 - x0) * SCALE))
H = int(round((y1 - y0) * SCALE))

# Brightness bands from the body's own luminance distribution.
body = np.concatenate([l[a > 200] for l, a in zip(lum, alpha)])
t_mid, t_hi = np.percentile(body, [38, 72])
print('bands', t_mid, t_hi, 'grid', W, H)


def contours(mask):
    mask = mask.astype(np.uint8) * 255
    mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((2, 2), np.uint8))
    found, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    out = []
    for c in found:
        if cv2.contourArea(c) < MIN_AREA:
            continue
        c = cv2.approxPolyDP(c, EPS, True).reshape(-1, 2)
        if len(c) < 3:
            continue
        pts = []
        for x, y in c:
            pts.append(int(round((x - x0) * SCALE)))
            pts.append(int(round((y - y0) * SCALE)))
        out.append(pts)
    return out


frames = []
for i in range(COUNT):
    a = alpha[i] > 128
    l = lum[i]
    layers = [contours(a), contours(a & (l >= t_mid)), contours(a & (l >= t_hi))]
    frames.append(layers)

with open(out_js, 'w', encoding='utf8') as fh:
    fh.write('// Generated by tools/build_coach.py from the CC0 Quaternius Universal Animation\n')
    fh.write('// Library (Jog_Fwd_Loop), rendered from behind in Blender. Do not edit by hand.\n')
    fh.write('// One run cycle (two steps) sampled in %d phases; each frame has 3 nested\n' % COUNT)
    fh.write('// brightness layers (silhouette, mid, lit) of flat polygons [x0,y0,x1,y1,...].\n')
    fh.write('export const COACH_WIDTH = %d;\nexport const COACH_HEIGHT = %d;\n' % (W, H))
    fh.write('export const COACH_FRAME_COUNT = %d;\n' % COUNT)
    fh.write('// Native tempo of the source animation: 22.4 frames at 30 fps per two steps.\n')
    fh.write('export const COACH_BASE_CADENCE = 160.7;\n')
    fh.write('// Phase (0..1 of the cycle) at which a foot lands; the other lands half a cycle later.\n')
    fh.write('export const COACH_FOOT_STRIKE = 0.042;\n')
    fh.write('export const COACH_FRAMES = ')
    json.dump(frames, fh, separators=(',', ':'))
    fh.write(';\n')

size = len(json.dumps(frames, separators=(',', ':')))
print('frames json bytes', size)

if preview:
    cell_w, cell_h = W * 2, H * 2
    cols = 6
    sheet = Image.new('RGB', (cols * cell_w, 4 * cell_h), (0, 0, 0))
    d = ImageDraw.Draw(sheet)
    shades = [(10, 70, 24), (25, 150, 52), (64, 255, 94)]
    for i, layers in enumerate(frames):
        ox, oy = (i % cols) * cell_w, (i // cols) * cell_h
        for shade, polys in zip(shades, layers):
            for p in polys:
                d.polygon([(ox + p[k] * 2, oy + p[k + 1] * 2) for k in range(0, len(p), 2)], fill=shade)
    sheet.save(preview)
